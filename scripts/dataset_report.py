"""Write the generated part of the dataset report (D3) from the bundle's fold CSVs.

Usage:
    uv run python scripts/dataset_report.py [--bundle DIR] [--out FILE]

Only the metadata CSVs are read, never the audio. Everything above the marker line in
the output file is hand-written and kept; everything below it is replaced.
"""

import argparse
from pathlib import Path

import yaml

from acousticwise.data.report import build_report, format_report, missing_classes

MARKER = "<!-- Generated by scripts/dataset_report.py: edits below this line are overwritten. -->"
FOLDS = [1, 2, 3, 4, 5]


def generated_section(bundle: Path, window_seconds: float) -> str:
    """The per-fold tables, then the splits with no clips of some class."""
    rows = build_report(bundle, FOLDS, window_seconds)
    lines = [
        MARKER,
        "",
        "## Counts per fold",
        "",
        "Vessels or days: distinct vessels (MMSI), or distinct days for background.",
        f"Short clips: shorter than the {window_seconds:g} s window, so padded before features.",
        "",
        format_report(rows).replace("## Fold", "### Fold"),
        "## Classes with no clips",
        "",
        "These splits cannot score the listed classes.",
        "",
        "| Fold | Split | Classes |",
        "|---:|---|---|",
    ]
    for (fold, split), labels in missing_classes(rows).items():
        lines.append(f"| {fold} | {split} | {', '.join(labels)} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", default="configs/default.yaml")
    parser.add_argument(
        "--bundle", help="bundle folder with fold_1 … fold_5 (default: data.bundle_dir)"
    )
    parser.add_argument("--out", default="docs/dataset-report.md")
    args = parser.parse_args()

    with open(args.config) as f:
        cfg = yaml.safe_load(f)
    bundle = Path(args.bundle or cfg["data"]["bundle_dir"])
    out = Path(args.out)

    written = out.read_text().split(MARKER)[0] if out.exists() else "# Dataset report\n\n"
    out.write_text(written + generated_section(bundle, cfg["audio"]["window_seconds"]))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
